<?php

namespace App\Services;

use Carbon\Carbon;
use InvalidArgumentException;

class HotspotPaymentSmsParser
{
    public function parse(string $sms): array
    {
        /*
        |--------------------------------------------------------------------------
        | NORMALIZE SMS
        |--------------------------------------------------------------------------
        */

        $sms = trim(
            preg_replace('/\s+/', ' ', $sms)
        );

        /*
        |--------------------------------------------------------------------------
        | VALIDATE PAYMENT SMS
        |--------------------------------------------------------------------------
        */

        if (! str_contains($sms, 'Kumbukumbu No.:')) {
            throw new InvalidArgumentException(
                'SMS hii haitambuliki kama SMS ya malipo ya Lipa Kwa Simu.'
            );
        }

        /*
        |--------------------------------------------------------------------------
        | PROVIDER
        |--------------------------------------------------------------------------
        */

        $provider = $this->detectProvider($sms);

        /*
        |--------------------------------------------------------------------------
        | AMOUNT
        |--------------------------------------------------------------------------
        */

        preg_match(
            '/TSh\s*([\d,]+(?:\.\d{1,2})?)/i',
            $sms,
            $amountMatch
        );

        /*
        |--------------------------------------------------------------------------
        | REFERENCE
        |--------------------------------------------------------------------------
        */

        preg_match(
            '/Kumbukumbu No\.:\s*(\d+)/i',
            $sms,
            $referenceMatch
        );

        /*
        |--------------------------------------------------------------------------
        | DATE + TIME
        |--------------------------------------------------------------------------
        */

        preg_match(
            '/(\d{2}\/\d{2}\/\d{2})\s+(\d{2}:\d{2})/',
            $sms,
            $dateMatch
        );

        /*
        |--------------------------------------------------------------------------
        | PAYER
        |--------------------------------------------------------------------------
        */

        [$payerPhone, $payerName] =
            $this->extractPayer(
                $sms,
                $provider
            );

        /*
        |--------------------------------------------------------------------------
        | REQUIRED DATA
        |--------------------------------------------------------------------------
        */

        if (
            empty($amountMatch[1]) ||
            empty($referenceMatch[1]) ||
            empty($dateMatch[1]) ||
            empty($dateMatch[2])
        ) {
            throw new InvalidArgumentException(
                'Baadhi ya taarifa muhimu hazikupatikana kwenye SMS.'
            );
        }

        if (! $payerPhone) {
            throw new InvalidArgumentException(
                'Namba ya simu ya aliyefanya malipo haikupatikana kwenye SMS.'
            );
        }

        /*
        |--------------------------------------------------------------------------
        | AMOUNT
        |--------------------------------------------------------------------------
        */

        $amount = (float) str_replace(
            ',',
            '',
            $amountMatch[1]
        );

        /*
        |--------------------------------------------------------------------------
        | PAYMENT DATE
        |--------------------------------------------------------------------------
        */

        $paidAt = Carbon::createFromFormat(
            'd/m/y H:i',
            $dateMatch[1] . ' ' . $dateMatch[2],
            config('app.timezone')
        );

        /*
        |--------------------------------------------------------------------------
        | RESULT
        |--------------------------------------------------------------------------
        */

        return [
            'provider' => $provider,

            'amount' => $amount,

            'payer_phone' =>
                $this->normalizePhone(
                    $payerPhone
                ),

            'payer_name' => $payerName,

            'reference' =>
                $referenceMatch[1],

            'paid_at' => $paidAt,

            'raw_sms' => $sms,

            'status' => 'pending',
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | DETECT PROVIDER
    |--------------------------------------------------------------------------
    */

    private function detectProvider(
        string $sms
    ): string {
        /*
        |--------------------------------------------------------------------------
        | M-PESA / VODACOM
        |--------------------------------------------------------------------------
        */

        if (
            preg_match(
                '/kutoka kwa\s+Vodacom;/i',
                $sms
            )
        ) {
            return 'MPESA';
        }

        /*
        |--------------------------------------------------------------------------
        | HALOPESA
        |--------------------------------------------------------------------------
        */

        if (
            preg_match(
                '/kutoka kwa\s+Halopesa;/i',
                $sms
            )
        ) {
            return 'HALOPESA';
        }

        /*
        |--------------------------------------------------------------------------
        | AIRTEL MONEY
        |--------------------------------------------------------------------------
        */

        if (
            preg_match(
                '/kutoka kwa\s+Airtel Money;/i',
                $sms
            )
        ) {
            return 'AIRTELMONEY';
        }

        /*
        |--------------------------------------------------------------------------
        | YAS
        |--------------------------------------------------------------------------
        */

        if (
            preg_match(
                '/kwenye\s+Lipa\s+namba/i',
                $sms
            )
        ) {
            return 'YAS';
        }

        return 'UNKNOWN';
    }

    /*
    |--------------------------------------------------------------------------
    | EXTRACT PAYER
    |--------------------------------------------------------------------------
    */

    private function extractPayer(
        string $sms,
        string $provider
    ): array {
        $pattern = match ($provider) {

            /*
            |--------------------------------------------------------------------------
            | YAS
            |--------------------------------------------------------------------------
            */

            'YAS' =>
                '/kutoka kwa\s+(255\d+)\s*-\s*(.+?)\.\s*Kumbukumbu No\.:/i',

            /*
            |--------------------------------------------------------------------------
            | M-PESA / HALOPESA / AIRTEL MONEY
            |--------------------------------------------------------------------------
            */

            'MPESA',
            'HALOPESA',
            'AIRTELMONEY' =>
                '/kutoka kwa\s+[^;]+;\s*(255\d+)\s*-\s*(.+?)\s+Kumbukumbu No\.:/i',

            default =>
                null,
        };

        if (! $pattern) {
            return [
                null,
                null,
            ];
        }

        preg_match(
            $pattern,
            $sms,
            $match
        );

        return [
            $match[1] ?? null,

            isset($match[2])
                ? trim(
                    $match[2],
                    " ."
                )
                : null,
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | NORMALIZE PHONE
    |--------------------------------------------------------------------------
    */

    private function normalizePhone(
        string $phone
    ): string {
        $phone = preg_replace(
            '/\D+/',
            '',
            $phone
        );

        /*
        |--------------------------------------------------------------------------
        | 255659840000
        |--------------------------------------------------------------------------
        */

        if (
            str_starts_with(
                $phone,
                '255'
            )
        ) {
            return $phone;
        }

        /*
        |--------------------------------------------------------------------------
        | 0659840000
        |--------------------------------------------------------------------------
        */

        if (
            str_starts_with(
                $phone,
                '0'
            )
            &&
            strlen($phone) === 10
        ) {
            return '255'
                .
                substr(
                    $phone,
                    1
                );
        }

        /*
        |--------------------------------------------------------------------------
        | 659840000
        |--------------------------------------------------------------------------
        */

        if (
            strlen($phone) === 9
        ) {
            return '255'
                .
                $phone;
        }

        return $phone;
    }
}